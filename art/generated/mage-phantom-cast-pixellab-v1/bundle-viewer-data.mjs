import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

export function bundleViewerData(){
  const directory=new URL('./',import.meta.url);
  const read=file=>JSON.parse(readFileSync(new URL(file,directory),'utf8'));
  const data={animation:read('animation.json'),runtime:read('reference/runtime-clips.json')};
  writeFileSync(new URL('viewer-data.js',directory),'// Generated by bundle-viewer-data.mjs; supports direct local-file viewing.\nwindow.phantomViewerData = '+JSON.stringify(data)+';\n');
}

if(process.argv[1]===fileURLToPath(import.meta.url))bundleViewerData();
